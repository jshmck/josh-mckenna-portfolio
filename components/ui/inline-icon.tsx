type InlineIconProps = {
  name: InlineIconName;
  /** Accessible name, read in place of the icon. Defaults to the icon's
   *  own name ("car", "cloud", "heart") -- the icons stand in for a word,
   *  so that is usually the right thing for a screen reader to say. */
  label?: string;
  /** For the rare purely-decorative use: hides the icon from assistive
   *  tech instead of naming it. */
  decorative?: boolean;
};

export function InlineIcon({ name, label = name, decorative = false }: InlineIconProps) {
  const icon = ICONS[name];
  const a11y = decorative
    ? ({ "aria-hidden": true } as const)
    : ({ role: "img", "aria-label": label } as const);
  return (
    <svg viewBox={icon.viewBox} className={`icon-inline ${icon.className}`} {...a11y}>
      <path d={icon.d} fillRule={icon.fillRule} clipRule={icon.fillRule} />
    </svg>
  );
}
